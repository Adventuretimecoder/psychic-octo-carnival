// Extracts only the game-icons.net paths the game references into a small module.
// Icons: game-icons.net (CC BY 3.0) — see CREDITS.md.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const icons = JSON.parse(readFileSync('node_modules/@iconify-json/game-icons/icons.json', 'utf8')).icons;
const used = new Set();
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(f) && !f.endsWith('.generated.ts')) {
      for (const m of readFileSync(p, 'utf8').matchAll(/['"`]([a-z0-9]+(?:-[a-z0-9]+)*)['"`]/g)) if (icons[m[1]]) used.add(m[1]);
    }
  }
};
walk('src');
const out = {};
for (const n of [...used].sort()) {
  const m = /d="([^"]+)"/.exec(icons[n].body);
  if (m) out[n] = m[1];
}
writeFileSync('src/assets/icons.generated.ts', `// Generated by scripts/build-icons.mjs — do not edit. Icons by game-icons.net contributors, CC BY 3.0.\nexport const ICON_PATHS: Record<string, string> = ${JSON.stringify(out)};\n`);
console.log(`icons: ${Object.keys(out).length}`);
