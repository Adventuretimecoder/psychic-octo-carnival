import type { CreatureDef, Element, EnemyBehavior, Rarity, BloodType } from '../types';

type Fam = CreatureDef['family'];
type Shape = CreatureDef['look']['shape'];

const el = (s: string): Element[] => (s ? (s.split(',') as Element[]) : []);

/** Compact creature factory. drops: 'id:chance id:chance'. tags: space separated. */
function c(
  id: string, name: string, family: Fam, behavior: EnemyBehavior,
  shape: Shape, color: string, accent: string, size: number,
  hp: number, damage: number, speed: number, armor: number,
  element: Element, weak: string, resist: string,
  rarity: Rarity, difficulty: 1 | 2 | 3 | 4 | 5,
  drops: string, blood: BloodType, xp: number, tags: string,
  abilities: string, habitat: string, appearance: string, lore: string, special?: string,
): CreatureDef {
  return {
    id, name, family, behavior, look: { shape, color, accent, size },
    hp, damage, speed, armor, element, weak: el(weak), resist: el(resist),
    abilities: abilities.split('|'), rarity, habitat, difficulty,
    drops: drops.split(' ').map((d) => { const [i, ch] = d.split(':'); return { id: i, chance: Number(ch) }; }),
    blood, xp, tags: [...tags.split(' '), element], lore, appearance, ...(special ? { special } : {}),
  };
}

