import type { BossDef, BossPattern, BloodType, Element } from '../types';

type Ph = [at: number, name: string, patterns: BossPattern[], speedMul: number, line: string];
const el = (s: string): Element[] => (s ? (s.split(',') as Element[]) : []);

function b(
  id: string, name: string, title: string, lore: string,
  shape: BossDef['look']['shape'], color: string, accent: string, size: number,
  hp: number, damage: number, speed: number, armor: number,
  element: Element, weak: string, resist: string,
  phases: Ph[], drops: string, blood: BloodType, xp: number, legendary: boolean, achievement: string,
): BossDef {
  return {
    id, name, title, lore, look: { shape, color, accent, size },
    hp, damage, speed, armor, element, weak: el(weak), resist: el(resist),
    phases: phases.map(([at, pn, patterns, speedMul, line]) => ({ at, name: pn, patterns, speedMul, line })),
    drops: [{ id: `relic-${id}`, chance: 1 }, ...drops.split(' ').map((d) => { const [i, ch] = d.split(':'); return { id: i, chance: Number(ch) }; })],
    blood, xp, ...(legendary ? { legendary: true } : {}), achievement,
  };
}

