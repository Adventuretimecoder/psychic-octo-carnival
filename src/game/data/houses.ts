import type {
  AbilityDef, AbilityKind, AbilityParams, AbilitySchool, BloodType, Element, HouseDef, ItemTemplate,
  MinionType, Modifier, QuestObjective, Rarity, WeaponType,
} from '../types';

type P = Partial<AbilityParams>;
type TierSpec = [name: string, params: P, note: string];

function sig(
  house: string, name: string, school: AbilitySchool, element: Element, kind: AbilityKind,
  icon: string, color: string, description: string, params: AbilityParams, note0: string,
  t1: TierSpec, t2: TierSpec, scaling: AbilityDef['scaling'],
): AbilityDef {
  return {
    id: `house-${house}`, name, school, element, kind, icon, color, description, params,
    tiers: [
      { name, mastery: 1, params: {}, note: note0 },
      { name: t1[0], mastery: 4, params: t1[1], note: t1[2] },
      { name: t2[0], mastery: 8, params: t2[1], note: t2[2] },
    ],
    unlock: { type: 'house', house }, scaling,
  };
}

const kill = (tag: string, count: number, text: string): QuestObjective => ({ type: 'kill', tag, count, text });
const boss = (b: string, text: string): QuestObjective => ({ type: 'boss', boss: b, text });
const depth = (region: string, floor: number, text: string): QuestObjective => ({ type: 'depth', region, floor, text });
const feed = (blood: BloodType | 'any', count: number, text: string): QuestObjective => ({ type: 'feed', blood, count, text });
const collect = (item: string, count: number, text: string): QuestObjective => ({ type: 'collect', item, count, text });
const standing = (house: string, value: number, text: string): QuestObjective => ({ type: 'standing', house, value, text });

function item(
  house: string, name: string, category: ItemTemplate['category'], icon: string, rarity: Rarity,
  description: string, mods: Modifier[], value: number,
  extra: { weaponType?: WeaponType; damage?: number; element?: Element; effect?: string } = {},
): ItemTemplate {
  return { id: `house-item-${house}`, name, category, icon, rarity, description, mods, value, ...extra };
}

