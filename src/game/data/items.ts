import type { Element, ItemCategory, ItemTemplate, Modifier, Rarity, StatKey, WeaponType } from '../types';

// Compact authoring helpers. A = flat add, M = multiplier (mul 0.1 = +10%).
const A = (stat: StatKey, add: number): Modifier => ({ stat, add });
const M = (stat: StatKey, mul: number): Modifier => ({ stat, mul });

/** Weapon: (id, name, type, rarity, damage, element, icon, description, mods, value, minLevel, effect?) */
const w = (
  id: string,
  name: string,
  weaponType: WeaponType,
  rarity: Rarity,
  damage: number,
  element: Element,
  icon: string,
  description: string,
  mods: Modifier[],
  value: number,
  minLevel: number,
  effect?: string,
): ItemTemplate => ({
  id,
  name,
  category: 'weapon',
  weaponType,
  rarity,
  damage,
  element,
  icon,
  description,
  mods,
  value,
  minLevel,
  ...(effect ? { effect } : {}),
});

/** Gear, relic or artifact: (category, id, name, rarity, icon, description, mods, value, minLevel, extra?) */
const g = (
  category: ItemCategory,
  id: string,
  name: string,
  rarity: Rarity,
  icon: string,
  description: string,
  mods: Modifier[],
  value: number,
  minLevel: number,
  extra: { setId?: string; effect?: string } = {},
): ItemTemplate => ({ id, name, category, rarity, icon, description, mods, value, minLevel, ...extra });

/** Consumable: (id, name, rarity, icon, description, use, value) */
const c = (
  id: string,
  name: string,
  rarity: Rarity,
  icon: string,
  description: string,
  use: NonNullable<ItemTemplate['use']>,
  value: number,
): ItemTemplate => ({ id, name, category: 'consumable', rarity, icon, description, mods: [], use, value, minLevel: 1 });

